using Guide12Examples.Models;

namespace Guide12Examples.Examples;

// =====================================================================
// GUIDE 12 - SECTION 1: Control Fundamentals and IDE Code
// ---------------------------------------------------------------------
// Lecture flow:
//  1. "The Control class provides the definitions for GUI objects."
//     -> Run the example and click "Inspect Button". Point out the chain
//        Button -> ButtonBase -> Control -> Component -> MarshalByRefObject -> Object
//        and the public property count (more than 80).
//  2. Component = containment and cleanup; MarshalByRefObject = can be
//     created on a remote computer and used by reference.
//     (Modern .NET no longer supports remoting, but the class is still
//     in the family tree, so the vocabulary still applies.)
//  3. "Widget" = general term for a GUI control.
//  4. IDE-generated code -> open Example01ControlFundamentalsForm.Designer.cs:
//       - InitializeComponent() holds every generated statement.
//       - Lines with "new" construct the controls:
//             sampleButton = new Button();
//       - SuspendLayout() pauses layout while properties are set;
//         ResumeLayout() turns it back on at the end.
//     These statements came from drag-and-drop code generation in the
//     Form Designer, not from typing.
//  5. Default event / default method: double-click sampleButton in the
//     Form Designer and Visual Studio jumps to sampleButton_Click below.
//     Click is the event users most likely expect from a Button.
//  6. Project > Add New Item lists many more item types (including Forms).
// =====================================================================
public partial class Example01ControlFundamentalsForm : Form
{
    public Example01ControlFundamentalsForm()
    {
        // Runs all of the IDE-generated code in the .Designer.cs file.
        InitializeComponent();

        outputTextBox.Text = "Click an \"Inspect\" button to examine a control.";
    }

    // DEFAULT METHOD: generated by double-clicking sampleButton in the designer.
    // It runs automatically when the default event (Click) occurs.
    private void sampleButton_Click(object sender, EventArgs e)
    {
        MessageBox.Show(
            "This is sampleButton_Click, the button's default method.\n\n" +
            "Visual Studio created this shell when the button was double-clicked " +
            "in the Form Designer, because Click is the event users most likely " +
            "expect from a Button.",
            "Default event: Click");
    }

    private void inspectButtonButton_Click(object sender, EventArgs e)
    {
        outputTextBox.Text = ControlInspector.Describe(sampleButton);
    }

    private void inspectLabelButton_Click(object sender, EventArgs e)
    {
        outputTextBox.Text = ControlInspector.Describe(sampleLabel);
    }

    private void inspectTextBoxButton_Click(object sender, EventArgs e)
    {
        outputTextBox.Text = ControlInspector.Describe(sampleTextBox);
    }

    // A Form is also a Control, so it has the same family tree (plus a few more ancestors).
    private void inspectFormButton_Click(object sender, EventArgs e)
    {
        outputTextBox.Text = ControlInspector.Describe(this);
    }
}
